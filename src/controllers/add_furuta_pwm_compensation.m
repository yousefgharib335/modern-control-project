function add_furuta_pwm_compensation(block,position,cfg)
% Invert the measured current map and accumulate subminimum pulse requests.
add_block('built-in/Subsystem',block,'Position',position);
add_block('simulink/Sources/In1',[block '/Controller Request'],'Position',[30 45 60 65]);
add_block('simulink/Sources/In1',[block '/Brake'],'Port','2','Position',[30 110 60 130]);
sampleTime = num2str(cfg.sampleTime,17);
add_block('simulink/Discrete/Zero-Order Hold',[block '/Sample Request'], ...
    'SampleTime',sampleTime,'Position',[100 39 160 71]);
add_block('simulink/Discrete/Zero-Order Hold',[block '/Sample Brake'], ...
    'SampleTime',sampleTime,'Position',[100 104 160 136]);
add_block('simulink/Discrete/Unit Delay',[block '/Pulse Remainder'], ...
    'SampleTime',sampleTime,'InitialCondition','0','Position',[100 175 160 205]);
add_block('simulink/User-Defined Functions/MATLAB Function', ...
    [block '/Voltage and Pulse Density'],'Position',[220 40 385 145]);
add_block('simulink/Sinks/Out1',[block '/Bridge Request'],'Position',[440 55 470 75]);
chart = find(sfroot,'-isa','Stateflow.EMChart','Path',[block '/Voltage and Pulse Density']);
inverse = pchip(cfg.current,cfg.voltage);
chart.Script = strjoin({ ...
    'function [voltage,next] = request(equivalentVoltage,brake,remainder)', ...
    sprintf('currentKnots = %s;',mat2str(cfg.current,17)), ...
    sprintf('inverseCoefficients = %s;',mat2str(inverse.coefs,17)), ...
    sprintf('target = %.17g*equivalentVoltage;',cfg.currentPerVolt), ...
    'voltage = 0;', ...
    'next = 0;', ...
    'if brake >= 0.5', ...
    '    return;', ...
    'end', ...
    'if abs(target) >= currentKnots(1)', ...
    '    magnitude = min(abs(target),currentKnots(end));', ...
    '    segment = min(sum(magnitude >= currentKnots),numel(currentKnots)-1);', ...
    '    offset = magnitude-currentKnots(segment);', ...
    '    voltage = sign(target)*polyval(inverseCoefficients(segment,:),offset);', ...
    '    next = remainder;', ...
    'else', ...
    '    next = remainder + target/currentKnots(1);', ...
    '    pulse = min(1,max(-1,round(next)));', ...
    sprintf('    voltage = pulse*%.17g;',cfg.voltage(1)), ...
    '    next = next-pulse;', ...
    'end', ...
    'end'},newline);
connect(block,'Controller Request/1','Sample Request/1');
connect(block,'Brake/1','Sample Brake/1');
connect(block,'Sample Request/1','Voltage and Pulse Density/1');
connect(block,'Sample Brake/1','Voltage and Pulse Density/2');
connect(block,'Pulse Remainder/1','Voltage and Pulse Density/3');
connect(block,'Voltage and Pulse Density/1','Bridge Request/1');
connect(block,'Voltage and Pulse Density/2','Pulse Remainder/1');
end

function connect(block,source,destination)
add_line(block,source,destination,'autorouting','on');
end
