function add_furuta_state_feedback_block(block,position,law,design)
% Build a full-state controller from its MATLAB source and design values.
folder = fileparts(mfilename('fullpath'));
add_block('simulink/User-Defined Functions/MATLAB Function',block,'Position',position);
chart = find(sfroot,'-isa','Stateflow.EMChart','Path',block);
chart.Script = char(strjoin([ ...
    "function [voltage,requestedVoltage] = controller(state)"; ...
    "K = " + string(mat2str(design.K,17)) + ";"; ...
    "voltageLimit = " + string(mat2str(design.voltageLimit,17)) + ";"; ...
    "[voltage,requestedVoltage] = " + string(law) + "(state,K,voltageLimit);"; ...
    "end"; string(fileread(fullfile(folder,[law '.m'])))],newline));
end
